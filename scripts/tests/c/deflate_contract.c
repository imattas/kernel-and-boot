#include <assert.h>
#include <stdint.h>
#include <string.h>
#include "../../../kernel/fs/btrfs/deflate.h"

int main(void) {
    static const uint8_t stored[] = {0x78, 0x01, 0x01, 0x03, 0x00, 0xfc, 0xff,
                                     'a', 'b', 'c', 0x02, 0x4d, 0x01, 0x27};
    static uint8_t fixed[] = {0x78, 0x9c, 0xcb, 0x48, 0xcd, 0xc9, 0xc9,
                              0x57, 0xc8, 0x40, 0x27, 0x01, 0x68, 0x03, 0x08, 0xb1};
    static const uint8_t dynamic[] = {
        0x78,0x9c,0xed,0xcb,0x59,0x02,0x42,0x00,0x00,0x40,0x41,0x29,0x54,0x28,0x25,0x2d,
        0x88,0xf6,0x52,0x68,0x51,0x59,0xe3,0xfe,0xb7,0x72,0x8d,0x3e,0xde,0xfc,0x8f,0xd0,
        0x11,0xbb,0x3d,0x49,0x56,0xfa,0x83,0xa1,0xaa,0xe9,0xa3,0xb1,0x31,0x99,0x9a,0x33,
        0x6b,0xbe,0x58,0xae,0x6c,0xc7,0x5d,0x7b,0xfe,0x66,0xbb,0xdb,0x1f,0x8e,0xa7,0xf3,
        0x25,0xb8,0xde,0xc2,0x28,0xbe,0x3f,0x9e,0xaf,0xe4,0xfd,0xf9,0xa6,0x59,0x5e,0x94,
        0xd5,0xaf,0x6e,0x04,0x3e,0x9f,0xcf,0xe7,0xf3,0xf9,0x7c,0x3e,0x9f,0xcf,0xe7,0xf3,
        0xf9,0x7c,0x3e,0x9f,0xcf,0xe7,0xf3,0xf9,0xfc,0x3f,0xfb,0x2d,0x4e,0x8a,0x13,0xae};
    uint8_t output[6400]; uint32_t size = 0;
    assert(btrfs_zlib_inflate(stored, sizeof(stored), output, sizeof(output), &size));
    assert(size == 3 && memcmp(output, "abc", 3) == 0);
    assert(btrfs_zlib_inflate(fixed, sizeof(fixed), output, sizeof(output), &size));
    assert(size == 23 && memcmp(output, "hello hello hello hello", 23) == 0);
    assert(btrfs_zlib_inflate(dynamic, sizeof(dynamic), output, sizeof(output), &size));
    assert(size == 6400);
    for (uint32_t i = 0; i < size; ++i) assert(output[i] == (uint8_t)(i & 63U));
    fixed[sizeof(fixed) - 1] ^= 1;
    assert(!btrfs_zlib_inflate(fixed, sizeof(fixed), output, sizeof(output), &size));
    return 0;
}
